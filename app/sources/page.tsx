import { getSources } from "@/lib/api";
import { USING_MOCK } from "@/lib/api";

const KIND_LABEL: Record<string, string> = {
  "mission-page": "Mission pages",
  image: "Imagery",
  model: "3D models",
  "press-kit": "Press kits",
};

export const metadata = {
  title: "Sources — Abandoned but not Forgotten",
};

export default async function SourcesPage() {
  const sources = await getSources();
  const kinds = Array.from(new Set(sources.map((s) => s.kind)));

  return (
    <div className="container">
      <section className="section-tight">
        <div className="eyebrow">Provenance</div>
        <h1 style={{ fontSize: "clamp(28px, 4vw, 40px)" }}>Sources</h1>
        <p className="lead">
          Every fact in this prototype is stored with a source id. These are the NASA pages,
          images and models behind it. NASA content is generally not subject to copyright in
          the United States; it is credited here as the source of the material.
        </p>
        <div className="row" style={{ marginTop: 10 }}>
          <span className="chip">{sources.length} sources</span>
          <span className="chip">{USING_MOCK ? "fixture data" : "live API"}</span>
          <span className="chip">no AI-generated imagery</span>
        </div>
      </section>

      {kinds.map((kind) => (
        <section key={kind} className="section-tight">
          <div className="eyebrow">{KIND_LABEL[kind] ?? kind}</div>
          <div className="stack">
            {sources
              .filter((s) => s.kind === kind)
              .map((s) => (
                <div key={s.id} className="card">
                  <div className="card-pad">
                    <div className="row" style={{ justifyContent: "space-between" }}>
                      <div>
                        <div className="card-title">{s.title}</div>
                        <div className="card-meta">{s.publisher}</div>
                      </div>
                      <a
                        className="btn btn-sm"
                        href={s.url}
                        target="_blank"
                        rel="noreferrer"
                      >
                        Open ↗
                      </a>
                    </div>
                  </div>
                </div>
              ))}
          </div>
        </section>
      ))}

      <section className="section-tight">
        <div className="card">
          <div className="card-pad">
            <div className="card-title">What is and is not generated</div>
            <p className="card-meta" style={{ marginTop: 8 }}>
              All text, facts and figures on this prototype come from NASA mission pages and
              stored records. No text or imagery was generated by AI. Imagery is NASA
              public-domain material served from NASA's image library; 3D models are NASA 3D
              Resources assets. The mission profiles use a fixed, curated set of phases.
            </p>
          </div>
        </div>
      </section>
    </div>
  );
}
